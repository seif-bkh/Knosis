The lighthouse had not spoken in eleven years, and Nora had stopped
apologising for it. She climbed the stairs each evening anyway, counting
them under her breath, because the counting was the only part of the day
that never argued with her.

At the top there was a lamp that no longer turned, a chair that had
outlived two keepers, and a window facing a sea that could not decide
what colour it was. She sat. She watched. On clear nights the water held
the sky so exactly that she could not tell which one was reflecting the
other, and she liked that confusion. It seemed honest.

The village below had opinions about her. They said she was waiting for
a ship, which was romantic and wrong. They said she was waiting for a
person, which was closer and still wrong. What Nora was waiting for had
no shape yet. It felt like the moment before a word arrives, when you
know the meaning perfectly and simply cannot say it.

On the ninth of March a light appeared on the water where no light had
any business being. It was small, and it was steady, and it did not move
with the swell. Nora watched it for an hour without blinking more than
she had to. Then she went downstairs, found the old signal lamp, cleaned
forty years of salt from its glass, and carried it back up.

She sent three short flashes, because three was what her father had
taught her. Anyone out there. Anyone at all.

The small light waited. Then it answered: three short flashes, patient
and exact, as though it had been practising for a very long time.

Nora sat down on the floor of the lamp room, which she had not done
since she was a child, and laughed until her eyes stung. Eleven years of
silence, and the sea had learned to talk back.

She did not sleep. She sent the sequence again at midnight, and again
when the sky began to grey, and each time the answer came without
hurrying. By morning she had filled four pages of a notebook with marks
that meant nothing to anyone but her, and everything to her.

The village woke to find their keeper on the cliff path, wild-haired,
holding a notebook against her chest as though it might try to leave.
She told them there was something out there that could count. They told
her to get some rest.

So she went back up the stairs, counting them, and she sat in the chair
that had outlived two keepers, and she waited for evening the way other
people wait for news. The lamp that no longer turned stood beside her.
The sea took its time deciding on a colour.

That night the small light did not send three flashes. It sent four.

Nora leaned forward until her forehead touched the cold glass. Four. She
had never taught it four. She looked at the notebook, at the marks, at
eleven years of not speaking, and understood that the conversation had
just stopped being hers to lead.

She raised the signal lamp with both hands, and she answered.
